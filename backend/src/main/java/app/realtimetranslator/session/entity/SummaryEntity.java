package app.realtimetranslator.session.entity;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.time.Instant;
import java.util.UUID;

/**
 * JPA entity for the {@code summaries} table.
 * Each row is one summary generated for a meeting — either by auto-silence
 * detection or manual trigger. A meeting can have multiple summaries.
 *
 * {@code actionItems} stored as JSONB string (array of {who, what, deadline})
 * rather than a typed collection, because the schema is defined by GPT-4o output
 * and may evolve without requiring a migration.
 */
@Entity
@Table(name = "summaries")
@Getter
@Setter
@NoArgsConstructor
public class SummaryEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(name = "meeting_id", nullable = false)
    private UUID meetingId;

    // "auto_silence" or "manual" — how this summary was triggered.
    @Column(name = "trigger_type", nullable = false, length = 16)
    private String triggerType;

    // Markdown content generated by GPT-4o.
    @Column(name = "content", nullable = false, columnDefinition = "TEXT")
    private String content;

    // JSONB string — flexible schema controlled by GPT-4o prompt output.
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "action_items", columnDefinition = "jsonb")
    private String actionItems;

    @Column(name = "generated_at", nullable = false, updatable = false)
    private Instant generatedAt;

    // How many messages were included in this summary's context.
    @Column(name = "messages_count", nullable = false)
    private int messagesCount;

    @PrePersist
    protected void onCreate() {
        if (generatedAt == null) {
            generatedAt = Instant.now();
        }
    }
}
